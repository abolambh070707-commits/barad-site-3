// يمكن استخدام هذه الرموز داخل نص السؤال أو الجواب فتُستبدل بالقيمة الحالية تلقائياً
const tokens: Record<string, string> = {
  '{{warrantyDays}}': String(siteConfig.warrantyDays),
  '{{hoursText}}': siteConfig.hoursText,
  '{{phone}}': siteConfig.phoneDisplay,
  '{{payments}}': siteConfig.paymentMethods.join(' أو '),
};
const fill = (s: string) => Object.entries(tokens).reduce((acc, [k, v]) => acc.split(k).join(v), s);

export const faqs: FaqItem[] = (faqData.items ?? []).map((f) => ({ q: fill(f.q ?? ''), a: fill(f.a ?? '') }));

